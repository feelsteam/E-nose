/************************************************************************************************************
 * @file    main.c
 * @brief   HT32F52367 (BM53A367A) 控制 SSD1309 OLED
 *          完全對應 Arduino SSD1309_test.ino 的硬體 SPI 接線
 *
 * ============================================================
 * variant.h 確認腳位：Arduino SPI = HT_SPI1 (PC11/PC8/PC9/PC10)
 *   SPI0_PORT  = HT_SPI1  (Arduino SPI 物件)
 *   SPI0_SCK   = PC11 D13 (HT_SPI1 SCK)
 *   SPI0_MOSI  = PC8  D11 (HT_SPI1 MOSI)
 *   SPI0_MISO  = PC9  D12 (HT_SPI1 MISO)
 *   SPI0_SEL   = PC10 D10 (HT_SPI1 SS)
 *
 * ============================================================
 * 硬體接線：
 *   OLED CS  -> D10 (PC10)  OLED SCL -> D13 (PC11)
 *   OLED SDA -> D11 (PC8)   OLED RES -> D8  (PA14)
 *   OLED DC  -> D9  (PA15)
 *
 * ============================================================
 * 【SPI_SEL_HARDWARE 說明】
 *   SOFTWARE SEL 模式下，只要 SS 腳位(PC10)未透過 AFIO 接到 SPI1，
 *   SPI1 內部的 SS 輸入會偵測到異常狀態 → Mode Fault (bit5) = 1
 *   → SCK 停止輸出 → RXBNE 永遠不被設定 → 無限等待。
 *
 *   解法：改用 SPI_SEL_HARDWARE + PC10 設 AFIO_FUN_SPI。
 *   SPI1 硬體在每個 byte 傳送時自動控制 PC10 (CS)：
 *     CS 拉低 → 8 個 SCK → CS 拉高。
 *   對 SSD1309 這類每 byte 都有獨立 CS 的協議完全正確。
 *   DC (PA15) 仍由 GPIO 手動控制，在 CS 拉低前設定好即可。
 ***********************************************************************************************************/

